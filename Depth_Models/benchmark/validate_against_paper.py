def _strip_md_bold(s: str) -> str:
    return s.replace("**", "").strip()


def parse_reference_tables(md_path: str) -> dict:
    """
    Returns {(paper_method_name, split): {"RMSE": float, "MAE": float, "iRMSE": float, "iMAE": float}}
    Reads up to the "## DIFF" section (stops there).
    """
    with open(md_path) as f:
        lines = f.readlines()

    refs = {}
    current_split = None  # type: Optional[str]
    in_data_block = False
    header_seen = False

    for line in lines:
        stripped = line.strip()

        # Stop before the reconciliation diff section
        if stripped.startswith("## DIFF") or stripped.startswith("## Conclusion"):
            break

        # Detect split section headers.
        # Matches on dataset name so the reference file can be renumbered freely.
        if stripped.startswith("#"):
            up = stripped.upper()
            if "AURORA" in up or ("TABLE 4" in up and "TEST" in up):
                current_split = "TEST"
                in_data_block = False
                header_seen = False
                continue
            if "DENSE" in up:
                current_split = "DENSE"
                in_data_block = False
                header_seen = False
                continue

        if current_split is None:
            continue

        # Skip empty lines
        if not stripped or not stripped.startswith("|"):
            continue

        # The separator line (|---|...) marks start of data rows
        if re.match(r"^\|[-| ]+\|$", stripped):
            if header_seen:
                in_data_block = True
            continue

        # First pipe-row is the header
        if not header_seen:
            header_seen = True
            continue

        if not in_data_block:
            continue

        # Parse data row
        cols = [_strip_md_bold(c) for c in stripped.split("|")[1:-1]]
        if not cols:
            continue

        # Table 4: Method | Year | RMSE | MAE | iRMSE | iMAE | Params | Time
        # Table 5: Method | RMSE | MAE | iRMSE | iMAE
        try:
            if current_split == "TEST":
                if len(cols) < 6:
                    continue
                name, _year, rmse, mae, irmse, imae = cols[0], cols[1], cols[2], cols[3], cols[4], cols[5]
            else:  # DENSE
                if len(cols) < 5:
                    continue
                name, rmse, mae, irmse, imae = cols[0], cols[1], cols[2], cols[3], cols[4]
            # Strip "(Ours)" suffix used to mark the proposed method in the paper
            name = re.sub(r'\s*\(ours\)\s*$', '', name.strip(), flags=re.I)
            refs[(name, current_split)] = {
                "RMSE":  float(rmse.replace(",", "")),
                "MAE":   float(mae.replace(",", "")),
                "iRMSE": float(irmse.replace(",", "")),
                "iMAE":  float(imae.replace(",", "")),
            }
        except (ValueError, IndexError):
            continue

    return refs


def load_benchmark_json(json_dir: str, tag: str, split: str) -> Optional[dict]:
    path = os.path.join(json_dir, f"{tag}__{split}.json")
    if not os.path.exists(path):
        return None
    try:
        d = json.load(open(path))
        return d.get("groups", {}).get("ALL")
    except Exception:
        return None


def flag_rmse(ours: float, paper: float) -> bool:
    abs_diff = abs(ours - paper)
    rel_diff = abs_diff / paper if paper > 0 else float("inf")
    return rel_diff > 0.03 or abs_diff > 50.0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--json-dir", default=os.path.join(RZB, "json"))
    ap.add_argument("--ref",      default=os.path.join(RZB, "paper_reference_tables.md"))
    args = ap.parse_args()

    refs = parse_reference_tables(args.ref)
    if not refs:
        print("ERROR: could not parse any reference rows from", args.ref, file=sys.stderr)
        return 2

    # Build result records
    rows_pass: list = []
    rows_flag: list = []
    rows_missing_json: list = []

    for (paper_name, split), paper_metrics in sorted(refs.items(), key=lambda x: (x[0][1], x[0][0])):
        json_tag = PAPER_TO_JSON.get((paper_name, split))
        if json_tag is None:
            # No mapping defined — skip (won't happen if table is up to date)
            continue

        bench = load_benchmark_json(args.json_dir, json_tag, split)
        if bench is None:
            rows_missing_json.append((paper_name, split, json_tag))
            continue

        our_rmse  = bench.get("RMSE",  float("nan"))
        our_mae   = bench.get("MAE",   float("nan"))
        our_irmse = bench.get("iRMSE", float("nan"))
        our_imae  = bench.get("iMAE",  float("nan"))

        p_rmse  = paper_metrics["RMSE"]
        p_mae   = paper_metrics["MAE"]
        p_irmse = paper_metrics["iRMSE"]
        p_imae  = paper_metrics["iMAE"]

        flagged = flag_rmse(our_rmse, p_rmse)
        rel_rmse = (our_rmse - p_rmse) / p_rmse * 100 if p_rmse else float("nan")
        rel_mae  = (our_mae  - p_mae)  / p_mae  * 100 if p_mae  else float("nan")

        record = dict(
            paper_name=paper_name, split=split, json_tag=json_tag,
            our_rmse=our_rmse, p_rmse=p_rmse, rel_rmse=rel_rmse,
            our_mae=our_mae,   p_mae=p_mae,   rel_mae=rel_mae,
            our_irmse=our_irmse, p_irmse=p_irmse,
            our_imae=our_imae,   p_imae=p_imae,
            flagged=flagged,
            known_reason=KNOWN_FLAGS.get((json_tag, split), ""),
        )
        if flagged:
            rows_flag.append(record)
        else:
            rows_pass.append(record)

    # ─── Print PASS table ───────────────────────────────────────────────────
    w = 26
    hdr = (f"{'Method (JSON tag)':<{w}} {'Split':<6} "
           f"{'OurRMSE':>9} {'PaperRMSE':>9} {'RelDiff%':>9}  "
           f"{'OurMAE':>7} {'PaperMAE':>7}  "
           f"{'OurIRMSE':>9} {'PaperIRMSE':>10}")
    sep = "-" * len(hdr)

    print("\n" + "=" * 70)
    print(f"  validate_against_paper.py — {datetime.date.today()}")
    print(f"  Ref: {os.path.basename(args.ref)}")
    print(f"  Thresholds: |rel RMSE| > 3%  OR  |abs RMSE diff| > 50 mm → FLAG")
    print("=" * 70)

    print(f"\n{'PASS rows':─^70}")
    print(hdr)
    print(sep)
    for r in rows_pass:
        print(f"{r['json_tag']:<{w}} {r['split']:<6} "
              f"{r['our_rmse']:>9.2f} {r['p_rmse']:>9.2f} {r['rel_rmse']:>+9.1f}%  "
              f"{r['our_mae']:>7.2f} {r['p_mae']:>7.2f}  "
              f"{r['our_irmse']:>9.2f} {r['p_irmse']:>10.2f}")

    print(f"\n{'FLAG rows':─^70}")
    if rows_flag:
        print(hdr)
        print(sep)
        for r in rows_flag:
            reason = f"  <- KNOWN: {r['known_reason']}" if r["known_reason"] else "  <- UNEXPLAINED"
            print(f"{r['json_tag']:<{w}} {r['split']:<6} "
                  f"{r['our_rmse']:>9.2f} {r['p_rmse']:>9.2f} {r['rel_rmse']:>+9.1f}%  "
                  f"{r['our_mae']:>7.2f} {r['p_mae']:>7.2f}  "
                  f"{r['our_irmse']:>9.2f} {r['p_irmse']:>10.2f}"
                  f"\n{' '*(w+7)}{reason}")
    else:
        print("  (none)")

    # ─── Methods in benchmark but not in paper ──────────────────────────────
    json_tags_with_split = set()
    for fn in os.listdir(args.json_dir):
        m = re.match(r"^(.+)__(TEST|DENSE)\.json$", fn)
        if m:
            json_tags_with_split.add((m.group(1), m.group(2)))

    paper_json_pairs = {(v, k[1]) for k, v in PAPER_TO_JSON.items()}
    no_ref = sorted(json_tags_with_split - paper_json_pairs)

    print(f"\n{'No-paper-ref rows (informational)':─^70}")
    if no_ref:
        for tag, split in no_ref:
            bench = load_benchmark_json(args.json_dir, tag, split)
            rmse_str = f"RMSE={bench['RMSE']:.1f}mm" if bench and "RMSE" in bench else "no data"
            print(f"  {tag}__{split}: {rmse_str}")
    else:
        print("  (all benchmark methods have paper references)")

    # ─── Missing JSONs ───────────────────────────────────────────────────────
    if rows_missing_json:
        print(f"\n{'Missing JSONs (paper row with no benchmark JSON)':─^70}")
        for pname, split, tag in rows_missing_json:
            print(f"  paper: {pname} / {split}  ->  json tag: {tag}__{ split}.json NOT FOUND")

    # ─── Summary ─────────────────────────────────────────────────────────────
    n_pass = len(rows_pass)
    n_flag = len(rows_flag)
    n_miss = len(rows_missing_json)
    total  = n_pass + n_flag + n_miss

    print("\n" + "=" * 70)
    status = "ALL PASS" if n_flag == 0 else f"{n_flag} FLAGGED"
    print(f"  SUMMARY: {n_pass}/{total} PASS   {n_flag}/{total} FLAG   {n_miss}/{total} missing JSON")
    print(f"  OVERALL: {status}")
    print("=" * 70 + "\n")

    # Machine-readable summary line (parsed by run_and_validate.sh)
    # Format: VALIDATION_SUMMARY n_pass=N n_flag=M n_miss=K date=YYYY-MM-DD
    print(f"VALIDATION_SUMMARY n_pass={n_pass} n_flag={n_flag} n_miss={n_miss} "
          f"date={datetime.date.today()}")

    return 1 if n_flag > 0 else 0


if __name__ == "__main__":
    sys.exit(main())
