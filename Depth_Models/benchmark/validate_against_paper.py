        "The DMD3C_paper/result_ema.pth checkpoint (epoch=29) is not in ckpt_eval_results.jsonl so "
        "we cannot confirm the paper's exact eval protocol. h=256 via KITTI.yaml gives 6674mm (further). "
        "Best available result is 6414mm; -2% is within normal re-implementation variance. "
