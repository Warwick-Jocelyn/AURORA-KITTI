#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
validate_against_paper.py — permanent validation gate (PI request, 2026-06-29)

Parses paper_reference_tables.md (Tables 4 & 5) and diffs every
json/<method>__<split>.json "ALL" group against the paper ground-truth.

FLAG criteria (applied to RMSE only):
  |relative RMSE diff| > 3%  OR  |absolute RMSE diff| > 50 mm

Exit codes:
  0 — all paper-referenced rows PASS
  1 — one or more rows FLAGGED

Usage:
  python validate_against_paper.py [--json-dir json/] [--ref paper_reference_tables.md]
"""
import os, sys, re, json, argparse, datetime
from typing import Optional

RZB = os.path.dirname(os.path.abspath(__file__))

# ─── Paper-name → benchmark JSON tag mapping ──────────────────────────────────
# Paper uses shorthand abbreviations; JSON tags follow eval_batch.py conventions.
# Keys: (paper_name_in_md, split)
# Values: JSON method tag (without __SPLIT.json)
PAPER_TO_JSON = {  # (paper_name_in_md, split) -> json_tag
    # Table 4 — AURORA-KITTI TEST
    ("IPBasic(fast)",  "TEST"): "IPBasic-fast",
    ("IPBasic(multi)", "TEST"): "IPBasic-multiscale",
    ("S2Dense(SS)",    "TEST"): "S2D-SelfSup-ZeroShot",
    ("S2Dense(Su)",    "TEST"): "S2D-Sup-ZeroShot",
    ("BP-Net",         "TEST"): "BPNet",
    ("Marigold-DC",    "TEST"): "Marigold-DC",
    ("DMD3C",          "TEST"): "DMD3C-distilled",
    ("DA-V3",          "TEST"): "DepthAnythingV3",
    ("UniK3D",         "TEST"): "UniK3D",
    ("DDCD",           "TEST"): "DDCD",
    # Table 5 — DENSE TEST
    ("IPBasic(F)",     "DENSE"): "IPBasic-fast",
    ("IPBasic(M)",     "DENSE"): "IPBasic-multiscale",
    ("S2Dense(SS)",    "DENSE"): "S2D-SelfSup-ZeroShot",
    ("S2Dense(Su)",    "DENSE"): "S2D-Sup-ZeroShot",
    ("BP-Net",         "DENSE"): "BPNet",
    ("MarigoldDC",     "DENSE"): "Marigold-DC",
    ("DMD3C",          "DENSE"): "DMD3C-distilled",
    ("DA-V3",          "DENSE"): "DepthAnythingV3",
    ("UniK3D",         "DENSE"): "UniK3D",
    ("DDCD",           "DENSE"): "DDCD",
}

# Known, documented reasons for FLAG rows (for human-readable output only).
