#!/usr/bin/env python
"""
Generate final deliverables from deliverable1_raw.json / deliverable2_raw.json:
  - lidar_degradation_table.tex   (Deliverable 1, booktabs)
  - deliverable2_comparison.tex   (Deliverable 2, booktabs)
  - deliverable2_range_comparison.png / .pdf  (figure)
  - monotonicity.json             (per-metric / per-weather verdict)
No dataset access here -- pure post-processing of the two raw JSONs.
"""
import json
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

OUTDIR = "/path/to/aurora-root/PhD_Project_2025/Realism_updated/lidar_degradation"

d1 = json.load(open(os.path.join(OUTDIR, "deliverable1_raw.json")))
d2 = json.load(open(os.path.join(OUTDIR, "deliverable2_raw.json")))

CELLS = d1["cells"]
ORDER = [
    ("clear", "clear"),
    ("fog", "light"), ("fog", "moderate"), ("fog", "heavy"),
    ("rain", "light"), ("rain", "moderate"), ("rain", "heavy"),
    ("snow", "light"), ("snow", "moderate"), ("snow", "heavy"),
]


# ---------------------------------------------------------------- Deliverable 1 table
def fmt_pct(x):
    return f"{100*x:.2f}" if x == x else "--"  # NaN check


def fmt_m(x, nd=2):
    return f"{x:.{nd}f}" if x == x else "--"


rows_tex = []
for w, s in ORDER:
    v = CELLS[f"{w}|{s}"]
    wlabel = w.capitalize() if s == "clear" else ""
    slabel = "--" if s == "clear" else s.capitalize()
    rows_tex.append(
        f"{w.capitalize() if s=='clear' else (w.capitalize() if s=='light' else '')} & "
        f"{slabel} & {v['n_frames']} & "
        f"{fmt_pct(v['dropout_rate'])} & {fmt_pct(v['spurious_rate'])} & "
        f"{fmt_pct(v['perturbed_rate'])} & {fmt_pct(v['preserved_rate'])} & "
        f"{fmt_m(v['range_rmse_pert_m'])} & {fmt_m(v['eff_range_p95_m'])} & "
        f"{fmt_pct(v['near_range_clutter_ratio'])} \\\\"
    )

# Insert \midrule between weather groups
tex_lines = []
prev_w = None
for (w, s), line in zip(ORDER, rows_tex):
    if prev_w is not None and w != prev_w:
        tex_lines.append("\\midrule")
    tex_lines.append(line)
    prev_w = w

table1 = r"""% Auto-generated by make_outputs.py -- Deliverable 1 (RC3.3)
% Pixel-pooled INPUT-LiDAR degradation, paper's own DCD masks applied to
% (S_c = velodyne_raw_clean, S_w = velodyne_raw), pooled over AURORA VAL+TEST.
% t_valid=1e-3 m, tau=0.05. Dash (--) = undefined / no support (e.g. clear row
% has zero perturbed pixels so Range RMSE is N/A by construction).
\begin{table}[t]
\centering
\caption{Dataset-level LiDAR degradation of AURORA-KITTI input sparse LiDAR, pixel-pooled over VAL+TEST ($N$ = number of frames in cell). Rates computed from the paper's own DCD masks ($M_{\mathrm{drop}}, M_{\mathrm{spur}}, M_{\mathrm{pert}}, M_{\mathrm{keep}}$) applied to the paired clean/weather sparse projections. Eff.\ Range = mean of per-frame 95th-percentile valid depth (m); Near-Clutter = fraction of valid weather-LiDAR returns within 8\,m.}
\label{tab:lidar_degradation}
\begin{tabular}{llrrrrrrrr}
\toprule
Weather & Severity & $N$ & Dropout(\%) & Spurious(\%) & Perturbed(\%) & Preserved(\%) & Range RMSE(m) & Eff.\ Range(m) & Near-Clutter(\%) \\
\midrule
""" + "\n".join(tex_lines) + r"""
\bottomrule
\end{tabular}
\vspace{2pt}

{\footnotesize Notes: Rain-Light Range RMSE is computed from only $n{=}32$ perturbed pixels (perturbed rate $\approx 6\times10^{-6}$, i.e.\ essentially no rain-light returns exceed the $\tau{=}5\%$ tolerance) and should be treated as low-support / not statistically meaningful, unlike Rain-Moderate/Heavy ($n{=}8699,12673$). Fog's Range RMSE is non-monotonic (Moderate $>$ Heavy) even though Dropout/Spurious/Preserved/Eff.\,Range/Near-Clutter are all cleanly monotonic light$\to$moderate$\to$heavy; Snow shows comparatively weak/non-monotonic severity separation across most metrics (see monotonicity.json / findings.md for the full per-metric verdict).}
\end{table}
"""

with open(os.path.join(OUTDIR, "lidar_degradation_table.tex"), "w") as f:
    f.write(table1)
print("Wrote lidar_degradation_table.tex")

# ---------------------------------------------------------------- Monotonicity verdict
def seq(weather, key):
    return [CELLS[f"{weather}|{sev}"][key] for sev in ("light", "moderate", "heavy")]


def is_monotone(vals, increasing=True):
    if increasing:
        return all(vals[i] < vals[i + 1] for i in range(len(vals) - 1))
    else:
        return all(vals[i] > vals[i + 1] for i in range(len(vals) - 1))


metrics_dir = {
    "dropout_rate": True,
    "spurious_rate": True,
    "perturbed_rate": True,
    "preserved_rate": False,
    "range_rmse_pert_m": True,
    "eff_range_p95_m": False,
    "near_range_clutter_ratio": True,
}

mono = {}
for w in ("fog", "rain", "snow"):
    mono[w] = {}
    for metric, increasing in metrics_dir.items():
        vals = seq(w, metric)
        mono[w][metric] = {
            "values_light_mod_heavy": vals,
            "monotonic": bool(is_monotone(vals, increasing)),
            "expected_direction": "increasing" if increasing else "decreasing",
        }

with open(os.path.join(OUTDIR, "monotonicity.json"), "w") as f:
    json.dump(mono, f, indent=2)
print("Wrote monotonicity.json")

for w in ("fog", "rain", "snow"):
    print(f"\n[{w.upper()}]")
    for metric, r in mono[w].items():
        flag = "YES" if r["monotonic"] else "NO"
        print(f"  {metric:26s} {['%.4g'%v for v in r['values_light_mod_heavy']]}  monotone({r['expected_direction']})={flag}")

# ---------------------------------------------------------------- Deliverable 2: table + figure
G = d2["groups"]


def get(g, w, key):
    return G[g][w][key]


rows2 = []
for w in ("fog", "rain"):
    for g in ("AURORA-all", "AURORA-light_moderate", "DENSE-real"):
        v = G[g][w]
        rows2.append((w, g, v["n_frames"], v["eff_range_p95_m"], v["eff_range_mean_of_frame_max_m"],
                       v["near_range_clutter_ratio"], v["points_per_frame"]))

tex2_lines = []
prev_w = None
for w, g, n, p95, mx, near, ppf in rows2:
    if prev_w is not None and w != prev_w:
        tex2_lines.append("\\midrule")
    wcol = w.capitalize() if g == "AURORA-all" else ""
    tex2_lines.append(f"{wcol} & {g} & {n} & {p95:.2f} & {mx:.2f} & {100*near:.2f} & {ppf:.0f} \\\\")
    prev_w = w

# clear baseline rows appended separately
clear_rows = []
for g in ("AURORA-clear", "DENSE-clear"):
    v = G[g]["clear"]
    clear_rows.append(f"Clear (baseline) & {g} & {v['n_frames']} & {v['eff_range_p95_m']:.2f} & {v['eff_range_mean_of_frame_max_m']:.2f} & {100*v['near_range_clutter_ratio']:.2f} & {v['points_per_frame']:.0f} \\\\")

table2 = r"""% Auto-generated by make_outputs.py -- Deliverable 2 (reviewer-2 severity-matched realism)
% Observable stats only (no clean pair needed): effective range = mean of per-frame
% 95th-pct valid depth; Near-Clutter = fraction valid returns < 8 m.
% CAVEAT: DENSE and AURORA-KITTI velodyne_raw differ ~10x in point density even in
% CLEAR weather (see Clear baseline rows) -- absolute magnitudes are NOT directly
% comparable across datasets; see findings.md for clear-normalized ratios.
\begin{table}[t]
\centering
\caption{Severity-matched realism check: AURORA-KITTI (VAL+TEST) vs.\ real DENSE, observable LiDAR statistics only (no clean-pair required, so these transfer to real data). Clear-weather baseline rows included to expose the cross-dataset point-density gap that confounds naive absolute comparison.}
\label{tab:severity_matched_realism}
\begin{tabular}{llrrrrr}
\toprule
Weather & Group & $N$ & Eff.\ Range $p_{95}$(m) & Eff.\ Range(mean-max, m) & Near-Clutter(\%) & Pts/frame \\
\midrule
""" + "\n".join(tex2_lines) + r"""
\midrule
""" + "\n".join(clear_rows) + r"""
\bottomrule
\end{tabular}
\end{table}
"""

with open(os.path.join(OUTDIR, "deliverable2_comparison.tex"), "w") as f:
    f.write(table2)
print("\nWrote deliverable2_comparison.tex")

# ----- clear-normalized ratio table (fair comparison, controls for density confound) -----
norm_rows = {}
for w in ("fog", "rain"):
    clear_p95_a = G["AURORA-clear"]["clear"]["eff_range_p95_m"]
    clear_p95_d = G["DENSE-clear"]["clear"]["eff_range_p95_m"]
    clear_near_a = G["AURORA-clear"]["clear"]["near_range_clutter_ratio"]
    clear_near_d = G["DENSE-clear"]["clear"]["near_range_clutter_ratio"]
    for g, clear_p95, clear_near, src in [
        ("AURORA-all", clear_p95_a, clear_near_a, "aurora"),
        ("AURORA-light_moderate", clear_p95_a, clear_near_a, "aurora"),
        ("DENSE-real", clear_p95_d, clear_near_d, "dense"),
    ]:
        v = G[g][w]
        norm_rows[(w, g)] = {
            "eff_range_ratio_vs_own_clear": v["eff_range_p95_m"] / clear_p95,
            "near_clutter_delta_vs_own_clear": v["near_range_clutter_ratio"] - clear_near,
        }

print("\nClear-normalized (fair) comparison:")
for (w, g), r in norm_rows.items():
    print(f"  {w:5s} {g:24s} range_ratio={r['eff_range_ratio_vs_own_clear']:.3f}  near_clutter_delta={r['near_clutter_delta_vs_own_clear']:+.3f}")

with open(os.path.join(OUTDIR, "deliverable2_clear_normalized.json"), "w") as f:
    json.dump({f"{w}|{g}": r for (w, g), r in norm_rows.items()}, f, indent=2)

# per-severity normalized (fog only, has 3 severities both sides)
print("\nPer-severity clear-normalized (fog):")
fog_sev_groups = [
    ("AURORA-fog-light", "aurora"), ("AURORA-fog-moderate", "aurora"), ("AURORA-fog-heavy", "aurora"),
    ("DENSE-fog-light", "dense"), ("DENSE-fog-moderate", "dense"), ("DENSE-fog-heavy", "dense"),
]
fog_sev_norm = {}
for g, src in fog_sev_groups:
    clear_p95 = G["AURORA-clear"]["clear"]["eff_range_p95_m"] if src == "aurora" else G["DENSE-clear"]["clear"]["eff_range_p95_m"]
    clear_near = G["AURORA-clear"]["clear"]["near_range_clutter_ratio"] if src == "aurora" else G["DENSE-clear"]["clear"]["near_range_clutter_ratio"]
    v = G[g]["fog"]
    ratio = v["eff_range_p95_m"] / clear_p95
    delta = v["near_range_clutter_ratio"] - clear_near
    fog_sev_norm[g] = {"eff_range_ratio_vs_own_clear": ratio, "near_clutter_delta_vs_own_clear": delta}
    print(f"  {g:24s} range_ratio={ratio:.3f}  near_clutter_delta={delta:+.3f}")

with open(os.path.join(OUTDIR, "deliverable2_fog_severity_normalized.json"), "w") as f:
    json.dump(fog_sev_norm, f, indent=2)

# ---------------------------------------------------------------- Figure
hist_edges = np.array(d2["meta"]["hist_edges_m"])
centers = 0.5 * (hist_edges[:-1] + hist_edges[1:])

fig, axes = plt.subplots(2, 2, figsize=(12, 8))

for ax, w in zip(axes[0], ("fog", "rain")):
    for g, style in [("AURORA-all", dict(color="tab:blue", ls="--", label="AURORA-all")),
                      ("AURORA-light_moderate", dict(color="tab:orange", ls="-", label="AURORA-light+moderate")),
                      ("DENSE-real", dict(color="tab:green", ls="-", lw=2.5, label="DENSE (real)"))]:
        counts = np.array(G[g][w]["range_hist_counts"], dtype=float)
        counts = counts / counts.sum()  # normalize to density for shape comparison
        ax.plot(centers, counts, **style)
    ax.set_title(f"Range histogram (normalized) -- {w}")
    ax.set_xlabel("depth (m)")
    ax.set_ylabel("fraction of valid returns")
    ax.legend(fontsize=8)
    ax.set_xlim(0, 80)

for ax, w in zip(axes[1], ("fog", "rain")):
    groups = ["AURORA-all", "AURORA-light_moderate", "DENSE-real"]
    p95 = [G[g][w]["eff_range_p95_m"] for g in groups]
    near = [100 * G[g][w]["near_range_clutter_ratio"] for g in groups]
    xr = np.arange(len(groups))
    ax2 = ax.twinx()
    b1 = ax.bar(xr - 0.18, p95, width=0.36, color="tab:blue", label="Eff.range $p_{95}$ (m)")
    b2 = ax2.bar(xr + 0.18, near, width=0.36, color="tab:red", label="Near-clutter (%)")
    ax.set_xticks(xr)
    ax.set_xticklabels(["AURORA\nall", "AURORA\nlight+mod", "DENSE\nreal"], fontsize=8)
    ax.set_ylabel("Eff. range $p_{95}$ (m)", color="tab:blue")
    ax2.set_ylabel("Near-clutter (%)", color="tab:red")
    ax.set_title(f"Effective range / near-clutter bars -- {w}")

plt.tight_layout()
plt.savefig(os.path.join(OUTDIR, "deliverable2_range_comparison.png"), dpi=150)
plt.savefig(os.path.join(OUTDIR, "deliverable2_range_comparison.pdf"))
print("\nWrote deliverable2_range_comparison.png/.pdf")

# fog per-severity figure (light/moderate/heavy for both AURORA and DENSE)
fig2, ax = plt.subplots(1, 2, figsize=(11, 4.2))
sevs = ["light", "moderate", "heavy"]
a_p95 = [G[f"AURORA-fog-{s}"]["fog"]["eff_range_p95_m"] for s in sevs]
d_p95 = [G[f"DENSE-fog-{s}"]["fog"]["eff_range_p95_m"] for s in sevs]
a_near = [100 * G[f"AURORA-fog-{s}"]["fog"]["near_range_clutter_ratio"] for s in sevs]
d_near = [100 * G[f"DENSE-fog-{s}"]["fog"]["near_range_clutter_ratio"] for s in sevs]

x = np.arange(len(sevs))
ax[0].plot(x, a_p95, "o-", color="tab:blue", label="AURORA")
ax[0].plot(x, d_p95, "s-", color="tab:green", label="DENSE (real)")
ax[0].set_xticks(x); ax[0].set_xticklabels(sevs)
ax[0].set_ylabel("Eff. range $p_{95}$ (m)")
ax[0].set_title("Fog: effective range vs severity")
ax[0].legend()

ax[1].plot(x, a_near, "o-", color="tab:blue", label="AURORA")
ax[1].plot(x, d_near, "s-", color="tab:green", label="DENSE (real)")
ax[1].set_xticks(x); ax[1].set_xticklabels(sevs)
ax[1].set_ylabel("Near-clutter (%)")
ax[1].set_title("Fog: near-range clutter vs severity")
ax[1].legend()
plt.tight_layout()
plt.savefig(os.path.join(OUTDIR, "deliverable2_fog_severity_curves.png"), dpi=150)
plt.savefig(os.path.join(OUTDIR, "deliverable2_fog_severity_curves.pdf"))
print("Wrote deliverable2_fog_severity_curves.png/.pdf")
